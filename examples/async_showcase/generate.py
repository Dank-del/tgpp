#!/usr/bin/env python3
"""Derive the coroutine showcase from the maintained synchronous demo catalogue."""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from generate import clang_format, format_cpp  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    formatter = clang_format()
    sources = sorted((ROOT / "examples/showcase_bot/demos").glob("*.cpp"))
    sources.append(ROOT / "examples/showcase_bot/showcase/catalog.cpp")
    for source in sources:
        text = source.read_text(encoding="utf-8")
        text = text.replace('"showcase/catalog.hpp"', '"async_showcase/catalog.hpp"')
        text = text.replace('"catalog.hpp"', '"async_showcase/catalog.hpp"')
        text = text.replace("namespace showcase", "namespace async_showcase")
        text = text.replace("DemoContext", "AsyncDemoContext")
        if source.name == "catalog.cpp":
            text = text.replace(
                "tgpp::Message AsyncDemoContext::text",
                "tgpp::Task<tgpp::Message> AsyncDemoContext::text",
            )
            text = text.replace("return call(", "co_return co_await call(")
        else:
            text = text.replace(
                "[](AsyncDemoContext& ctx) {", "[](AsyncDemoContext& ctx) -> Task<void> {"
            )
            text = re.sub(r"\bctx\.(call|text|pause)\(", r"co_await ctx.\1(", text)
        text = "// Generated by examples/async_showcase/generate.py. DO NOT EDIT.\n" + text
        target = ROOT / "examples/async_showcase/generated" / source.name
        text = format_cpp(text, str(target.relative_to(ROOT)), formatter)
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                raise SystemExit(f"stale async showcase: {target.relative_to(ROOT)}")
        else:
            target.write_bytes(text.encode("utf-8"))
    print("Verified async showcase" if args.check else "Generated async showcase")


if __name__ == "__main__":
    main()
